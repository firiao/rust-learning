// 01. Hello, Rust!
//
// Запуск:
//   rustc --edition 2024 examples/01_hello.rs -o /tmp/hello
//   /tmp/hello
//
// Темы: main, println!, переменные, mut, shadowing, типы, функции, блоки.

fn main() {
    // println! — это макрос (восклицательный знак), а не функция.
    println!("Привет, Rust!");

    // По умолчанию переменные неизменяемы.
    let name = "Мир"; // &str — строковый литерал
    // name = "другой"; // ошибка: cannot assign twice to immutable variable

    // Хочешь менять — добавь mut.
    let mut counter = 0;
    counter += 1;

    // Тип можно указать явно, но обычно работает вывод типов.
    let age: u8 = 20;
    let pi = 3.1415_f64;

    // Затенение (shadowing): новая переменная с тем же именем,
    // может иметь другой тип.
    let spaces = "   ";
    let spaces = spaces.len();

    println!("name = {name}, counter = {counter}, age = {age}, pi = {pi}");
    println!("в строке {spaces} пробела (длина = {spaces})");

    // Форматирование
    println!("{:>7} | {:<7} | {:^7}", "справа", "слева", "центр");
    println!("{:.2}", 3.14159); // два знака после запятой
    println!("{:?}", (1, "два", 3.0)); // Debug-вывод кортежа

    // Функции объявляются отдельно, порядок не важен.
    let sum = add(2, 3);
    println!("2 + 3 = {sum}");

    // Блок — это выражение. Последнее выражение без ; возвращается.
    let result = {
        let x = 10;
        x * x
    };
    println!("result = {result}");

    // Упражнение: поменяй форматирование так, чтобы числа выровнялись
    // по правому краю в колонке шириной 10.
}

fn add(a: i32, b: i32) -> i32 {
    a + b // без ; — это возвращаемое значение
}
